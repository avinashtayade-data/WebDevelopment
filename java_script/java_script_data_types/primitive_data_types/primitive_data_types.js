/*
 primitive data types
 primitive data types represent a single data
  1.number[whole-numbers | decimal-numbers]
  2.string["" | ' ']
  3.boolean[true | false]
  4.undefined
  5.null
  6.bigint
  7.symbol
*/
// 1.number[whole-numbers | decimal-numbers]
let employeeID=1701;
console.log(employeeID,typeof employeeID);
const fuelCapacity=12;
console.log(fuelCapacity,typeof fuelCapacity);
let academicCGPA=9.65;
console.log(academicCGPA,typeof academicCGPA);

// 2.string["" | ' ']
let trainerName="Yashwanth";
console.log(trainerName,typeof trainerName);
let currentLearningCourse='JavaScript';
console.log(currentLearningCourse,typeof currentLearningCourse);

// 3.boolean[true | false]
let isTrainerAvailable=true;
console.log(isTrainerAvailable,typeof isTrainerAvailable);
let isTrainerOnline=false;
console.log(isTrainerOnline,typeof isTrainerOnline);
