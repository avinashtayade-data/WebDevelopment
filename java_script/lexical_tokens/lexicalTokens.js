/*
1.literals
literals are data or value which is directly written into the code.
examples:number-literals,string-literals,boolean-literals

2.keywords
keywords are pre-defined reserved english words which has special meaning which drives java script engine to perform specific operation
keywords should be written in lower-case
examples:if if else else if switch new for while do while

3.identifiers
identifiers are user-defined english words which should be readable to any developer
indentifiers should not start with special character and numbers, identifiers can be started with alphabets and _ or $
examples:
    1.variableNames[camelCasing] rollNumber universityRegNumber
    2.objectReferenceVariableNames[camelCasing] hpLaptopObject studentNames
    3.functionNames[camelCasing] getSquaredNumber getCircleArea getDistanceTravelled
    4.ClassNames[PascalCasing] Chair Student Employee
    5.ConstructorNames[PascalCasing] Chair Student Employee
    6.naming format _userOne _userTwo $information

4.operators
operators are the special characters or symbols which are used for performing arithmetic, logical, relational operations by using operands
examples:+ - * / % ** && || ! < > <= >=

5.seperators[punctuators]
seperators or punctuators are the special characters or symbols which are used for seperating, terminating and grouping lines of codes
examples:
    1.semi-colon ; 2.colon :[key:value] 3.= 4., 5.{} 6.[] 7.() 8.. 9." "
*/
